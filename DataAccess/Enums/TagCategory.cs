namespace Models.Enums;

/// <summary>
/// Категории тегов для классификации контента
/// </summary>
public enum TagCategory
{
    /// <summary>Жанр произведения (фэнтези, романтика, ужасы)</summary>
    Genre = 1,

    /// <summary>Основная тема или сюжетный элемент (путешествия, магия, политика)</summary>
    Theme = 2,

    /// <summary>Настроение/атмосфера (мрачный, светлый, меланхоличный)</summary>
    Mood = 3,

    /// <summary>Тип персонажей (сильный герой, антигерой, злодей)</summary>
    CharacterType = 4,

    /// <summary>Отношения между персонажами (от ненависти до любви, дружба)</summary>
    Relationship = 5,

    /// <summary>Сеттинг/мир (средневековье, киберпанк, современность)</summary>
    Setting = 6,

    /// <summary>Сюжетные тропы (медленное развитие, месть, тайна личности)</summary>
    Tropes = 7,

    /// <summary>Дополнительная информация (адаптировано, новелла, ранобэ)</summary>
    Other = 99
}